def table_head(ws, row, headers):
    for i, h in enumerate(headers, 1):
        c = ws.cell(row, i, ru(h))
        c.font = font(9, True, WHITE)
        c.fill = fill(GOLD if i == 1 else HEAD)
        c.alignment = center
        c.border = thin
    ws.row_dimensions[row].height = 18
    return row + 1


def table_row(ws, row, vals, prio=None):
    bg = ROW_A if row % 2 else ROW_B
    if prio in ("P0", "срочно"):
        bg = "FDECEC"
        prio = "срочно"
    elif prio in ("P1", "потом"):
        bg = "FEF3E8"
        prio = "потом"
    elif prio in ("P2", "позже"):
        bg = "EBF4FF"
        prio = "позже"
    vals = [ru(v) for v in vals]
    if vals and vals[-1] in PRIO_RU:
        vals[-1] = PRIO_RU[vals[-1]]
    for i, v in enumerate(vals, 1):
        c = ws.cell(row, i, v)
        c.font = font(9, i in (1, 6), P0 if prio == "срочно" and i == 6 else INK)
        c.fill = fill(bg)
        c.alignment = wrap
        c.border = thin
    ws.row_dimensions[row].height = 56
    return row + 1


