def title_block(ws, title, subtitle):
    title, subtitle = ru(title), ru(subtitle)
    ws.merge_cells("A1:F1")
    ws["A1"] = title
    ws["A1"].font = font(18, True, WHITE)
    ws["A1"].fill = fill(NAVY)
